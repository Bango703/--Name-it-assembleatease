#!/usr/bin/env node
// Service areas: every Easer gets offers only within their travel distance of
// their home ZIP, and every Texas ZIP is on the map (owner, 2026-11-21: "why are
// offers being sent to locations thats 200 miles away?" and "everyone should be
// in a located area").
//
// The defect this locks shut: the market gate failed OPEN for an Easer whose
// ZIP had no market. Whitehouse (75791, near Tyler) and Harker Heights (76548,
// Killeen) had none, so both were offered every job in Texas, including Houston
// booking AAE-WEIDRMMJRZ, 166 miles from Whitehouse.
//
// Runs the real eligibility step (findEligibleEasers) against an in-memory
// database. No network.
import assert from 'node:assert/strict';
import { readFileSync, existsSync } from 'node:fs';
import {
  SERVICE_MARKETS, TRAVEL_RADIUS_MILES, easerTravelRadiusMiles, isTexasZip, marketForZip,
  milesBetweenZips, serviceAreaCheck, zipLocation,
} from '../api/_source-of-truth.js';
import { TEXAS_ZIP_LOCATIONS, TEXAS_ZIP_LOCATIONS_SOURCE } from '../api/_texas-zip-locations.js';
import { findEligibleEasers, proximityScore } from '../api/booking/_dispatch-internal.js';
import { loadTravelRadii, normalizeTravelRadius } from '../api/_easer-work-preferences.js';
import { easersCovering } from '../api/_easer-coverage.js';
import { describeEaserServiceArea, knownMarketAreas } from '../api/_market-area.js';
import { CONTRACTOR_AGREEMENT_VERSION } from '../api/_assembler-onboarding.js';

process.env.EASER_MEMBERSHIP_ENABLED = 'false';
const read = (p) => readFileSync(new URL(`../${p}`, import.meta.url), 'utf8').replace(/\r\n/g, '\n');
let passed = 0;
async function check(name, fn) { await fn(); passed += 1; console.log(`  ok  ${name}`); }

// ── 1. The map ───────────────────────────────────────────────────────────────
await check('every Texas ZIP area has a Census point inside Texas', () => {
  const zips = Object.keys(TEXAS_ZIP_LOCATIONS);
  assert.ok(zips.length >= 1980, `only ${zips.length} ZIPs`);
  assert.match(TEXAS_ZIP_LOCATIONS_SOURCE, /Census Bureau \d{4} Gazetteer/);
  for (const zip of zips) {
    const [lat, lng] = TEXAS_ZIP_LOCATIONS[zip];
    assert.ok(isTexasZip(zip), `${zip} is not a Texas ZIP`);
    assert.ok(lat > 25 && lat < 37 && lng > -107 && lng < -93, `${zip} is outside Texas`);
  }
  assert.ok(existsSync(new URL('../scripts/build-texas-zip-locations.mjs', import.meta.url)), 'the table is reproducible');
  assert.match(read('api/_texas-zip-locations.js'), /^\/\/ GENERATED by scripts\/build-texas-zip-locations\.mjs/);
});

await check('every Texas ZIP is in exactly one market, and every market has a name', () => {
  const owner = new Map();
  for (const [market, prefixes] of Object.entries(SERVICE_MARKETS)) {
    for (const prefix of prefixes) {
      assert.ok(!owner.has(prefix), `${prefix} is in ${owner.get(prefix)} and ${market}`);
      assert.ok(isTexasZip(`${prefix === '885' ? '88510' : prefix + '01'}`), `${prefix} is not Texas`);
      owner.set(prefix, market);
    }
  }
  for (const zip of Object.keys(TEXAS_ZIP_LOCATIONS)) assert.ok(marketForZip(zip), `${zip} has no market`);
  for (const zip of ['73301', '88510', '77101']) assert.ok(marketForZip(zip), `${zip} has no market`);
  assert.equal(marketForZip('75791'), 'east_texas');
  assert.equal(marketForZip('76548'), 'waco_killeen');
  assert.equal(marketForZip('79830'), 'el_paso', '798 is the El Paso postal area, not Midland');
  for (const area of knownMarketAreas()) assert.ok(!/_/.test(area.marketLabel), `${area.marketKey} has no label`);
});

await check('a PO-box ZIP is placed at the nearest-numbered ZIP; a non-Texas ZIP is not placed at all', () => {
  assert.equal(zipLocation('78701').precision, 'zip');
  const po = zipLocation('77001');
  assert.equal(po.precision, 'nearby_zip');
  assert.equal(po.basedOn, '77002');
  assert.ok(zipLocation('77101'), 'an all-PO-box area (Houston 771) falls back within its market');
  for (const zip of ['99999', '10001', '7870', '', null, 'abcde']) assert.equal(zipLocation(zip), null, String(zip));
});

// ── 2. The rule ──────────────────────────────────────────────────────────────
await check('travel distance: the Easer chooses 15, 25, 50 or 75 miles; unset is 50', () => {
  assert.deepEqual([...TRAVEL_RADIUS_MILES.options], [15, 25, 50, 75]);
  assert.equal(TRAVEL_RADIUS_MILES.default, 50);
  assert.equal(easerTravelRadiusMiles({}), 50);
  assert.equal(easerTravelRadiusMiles({ travel_radius_miles: null }), 50);
  assert.equal(easerTravelRadiusMiles({ travel_radius_miles: 25 }), 25);
  assert.equal(easerTravelRadiusMiles({ travel_radius_miles: 500 }), 75, 'held to the platform maximum');
  assert.equal(easerTravelRadiusMiles({ travel_radius_miles: -3 }), 50);
  assert.deepEqual(normalizeTravelRadius(25), { ok: true, value: 25 });
  assert.equal(normalizeTravelRadius(40).ok, false);
  assert.equal(normalizeTravelRadius('lots').ok, false);
});

await check('the real cases: the far offers stop, every metro job we serve still goes out', () => {
  const at = (jobZip, easerZip, radius) => serviceAreaCheck(jobZip, { zip: easerZip, travel_radius_miles: radius });
  // The defect.
  assert.equal(at('77018', '75791').ok, false, 'Whitehouse is not offered Houston');
  assert.equal(at('77018', '75791').reason, 'too_far');
  assert.ok(at('77018', '75791').distanceMiles > 160);
  assert.equal(at('78701', '76548').ok, false, 'Harker Heights is not offered Austin at the default');
  assert.equal(at('78701', '76548', 75).ok, true, 'unless that Easer chooses 75 miles');
  assert.equal(at('78040', '78209', 75).ok, false, 'Laredo never goes to San Antonio');
  // What must keep working.
  assert.equal(at('75701', '75791').ok, true, 'Whitehouse gets Tyler');
  assert.equal(at('76502', '76548').ok, true, 'Harker Heights gets Temple');
  for (const zip of ['77494', '77389', '77584', '77573', '77520', '77550', '77301']) {
    assert.equal(at(zip, '77002').ok, true, `the Houston Easer gets Greater Houston ${zip}`);
  }
  for (const zip of ['78759', '78640', '78626', '78734', '78620', '78666']) {
    assert.equal(at(zip, '78660').ok, true, `the Pflugerville Easer gets Austin-area ${zip}`);
  }
  assert.equal(at('76102', '75227').ok, true, 'Dallas to Fort Worth');
  assert.equal(at('75227', '75409').ok, true, 'Anna to Dallas');
  assert.equal(at('79401', '79413').ok, true, 'Lubbock');
  assert.equal(at('78759', '78660', 15).ok, true, '10 miles is inside a 15-mile choice');
  assert.equal(at('78640', '78660', 15).ok, false, '34 miles is outside a 15-mile choice');
});

await check('fails closed: a job or an Easer off the map matches nobody', () => {
  assert.equal(serviceAreaCheck('10001', { zip: '78660' }).reason, 'job_location_unknown');
  assert.equal(serviceAreaCheck('78701', { zip: '99999' }).reason, 'easer_location_unknown');
  assert.equal(serviceAreaCheck('78701', {}).ok, false);
  assert.equal(milesBetweenZips('78701', '10001'), null);
});

await check('nearer Easers rank first: 75 points within 5 miles, none at the longest distance', () => {
  assert.equal(proximityScore(0), 75);
  assert.equal(proximityScore(5), 75);
  assert.equal(proximityScore(TRAVEL_RADIUS_MILES.max), 0);
  assert.equal(proximityScore(200), 0);
  assert.equal(proximityScore(null), 0);
  assert.ok(proximityScore(10) > proximityScore(30) && proximityScore(30) > proximityScore(50));
});

// ── 3. Dispatch runs it: the real eligibility step ───────────────────────────
const readyBase = {
  role: 'assembler', application_status: 'approved', status: 'active', tier: 'starter', identity_verified: true,
  is_available: true, phone: '+1 737 555 0100', sms_consent_at: '2026-07-12T12:00:00.000Z',
  contractor_agreement_signed_at: '2026-07-12T12:00:00.000Z', contractor_agreement_version: CONTRACTOR_AGREEMENT_VERSION,
  code_of_conduct_agreed_at: '2026-07-12T12:00:00.000Z', application_fee_waived: true, account_closure_status: null,
};
const EASERS = [
  { ...readyBase, id: 'whitehouse', full_name: 'Whitehouse Ready', zip: '75791', city: 'Whitehouse' },
  { ...readyBase, id: 'harker', full_name: 'Harker Heights Ready', zip: '76548', city: 'Harker Heights' },
  { ...readyBase, id: 'houston', full_name: 'Houston Ready', zip: '77002', city: 'Houston' },
  { ...readyBase, id: 'pflugerville', full_name: 'Pflugerville Ready', zip: '78660', city: 'Pflugerville' },
  { ...readyBase, id: 'no-zip', full_name: 'No ZIP', zip: null, city: 'Austin' },
];
function fakeDb({ radii = {}, radiusError = false } = {}) {
  const chainFor = (columns) => {
    const result = () => {
      if (columns === 'id') return { data: [], error: null };                          // demo accounts
      if (columns.startsWith('id, work_services')) return { data: [], error: null };   // no work preferences
      if (columns === 'id, owner_blocked_services') return { data: [], error: null };
      if (columns === 'id, travel_radius_miles') {
        return radiusError
          ? { data: null, error: { code: 'PGRST204', message: "column profiles.travel_radius_miles does not exist" } }
          : { data: Object.entries(radii).map(([id, miles]) => ({ id, travel_radius_miles: miles })), error: null };
      }
      return { data: EASERS, error: null };
    };
    const c = {
      eq() { return c; }, in() { return c; }, or() { return c; }, not() { return c; },
      is() { return c; }, order() { return c; }, limit() { return c; },
      then(resolve, reject) { return Promise.resolve(result()).then(resolve, reject); },
    };
    return c;
  };
  return { from(table) { assert.equal(table, 'profiles'); return { select: (cols) => chainFor(String(cols)) }; } };
}
const job = (zip) => ({ id: 'b', service: 'Mounting & Hanging', service_zip: zip, address: `1 Main St, TX ${zip}`, date: '2026-12-10', time: '9:00 AM - 11:00 AM' });
const offeredFor = async (zip, opts) => (await findEligibleEasers(fakeDb(opts), job(zip))).easers.map(e => e.id).sort();

await check('the Houston job (77018) goes only to the Houston Easer, never to Whitehouse', async () => {
  assert.deepEqual(await offeredFor('77018'), ['houston']);
});
await check('a Tyler job goes to Whitehouse; an Austin job to Pflugerville, and to Harker Heights only at 75 miles', async () => {
  assert.deepEqual(await offeredFor('75701'), ['whitehouse']);
  assert.deepEqual(await offeredFor('78701'), ['pflugerville']);
  assert.deepEqual(await offeredFor('78701', { radii: { harker: 75 } }), ['harker', 'pflugerville']);
  assert.deepEqual(await offeredFor('78759', { radii: { pflugerville: 15, harker: 25 } }), ['pflugerville'], '10 miles fits a 15-mile choice; 41 does not fit 25');
  assert.deepEqual(await offeredFor('78640', { radii: { pflugerville: 15 } }), [], 'Kyle is 34 miles from Pflugerville and 70 from Harker Heights');
});
await check('each offered Easer carries the distance dispatch measured', async () => {
  const found = await findEligibleEasers(fakeDb(), job('77018'));
  assert.equal(found.easers[0]._distanceMiles, milesBetweenZips('77018', '77002'));
  assert.equal(found.easers[0]._radiusMiles, 50);
});
await check('before migration 132 (no column) every Easer runs on the default distance', async () => {
  assert.deepEqual(await offeredFor('77018', { radiusError: true }), ['houston']);
  assert.equal((await loadTravelRadii(fakeDb({ radiusError: true }), ['houston'])).size, 0);
});
await check('nobody in range and an unplaceable job each say so, for the owner', async () => {
  const far = await findEligibleEasers(fakeDb(), job('79901'));
  assert.equal(far.easers.length, 0);
  assert.equal(far.code, 'NO_EASER_IN_RANGE');
  const off = await findEligibleEasers(fakeDb(), job('10001'));
  assert.equal(off.code, 'JOB_LOCATION_UNKNOWN');
  assert.match(off.message, /Assign it by hand/);
});

// ── 4. One rule everywhere ───────────────────────────────────────────────────
await check('"covered" on the booking page is the same rule as "offered"', async () => {
  const areas = [{ zip: '75791', travel_radius_miles: null }, { zip: '77002', travel_radius_miles: null }];
  assert.equal(easersCovering(areas, '77018'), 1, 'only the Houston Easer covers Houston');
  assert.equal(easersCovering(areas, '75701'), 1);
  assert.equal(easersCovering(areas, '78701'), 0);
  const coverage = read('api/_easer-coverage.js');
  assert.match(coverage, /return serviceAreaCheck\(String\(customerZip/);
  for (const file of ['api/booking/area-coverage.js', 'api/booking/promo-preview.js', 'api/cron/unassigned-escalation.js']) {
    assert.match(read(file), /activeEaserAreas\(/, `${file} reads Easer areas with their travel distance`);
  }
});
await check('dispatch has one area rule: no market gate, no ZIP-prefix match, no city match', () => {
  const src = read('api/booking/_dispatch-internal.js');
  assert.doesNotMatch(src, /isSameServiceMarket/);
  assert.doesNotMatch(src, /zipPrefix/, 'the job nudge uses the travel distance too');
  assert.match(src, /serviceAreaCheck\(bookingZip, \{ zip: e\.zip, travel_radius_miles: radii\.get\(e\.id\) \}\)\.ok/);
  assert.match(src, /score \+= proximityScore\(e\._distanceMiles\);/);
  assert.doesNotMatch(src, /e\.zip === bookingZip/);
});
await check('the owner and the Easer see the same area dispatch uses', () => {
  const whitehouse = describeEaserServiceArea({ zip: '75791', city: 'Whitehouse' });
  assert.equal(whitehouse.located, true);
  assert.equal(whitehouse.radiusMiles, 50);
  assert.equal(whitehouse.isDefault, true);
  assert.equal(whitehouse.areaLabel, 'Tyler, Longview and East Texas');
  assert.equal(describeEaserServiceArea({ zip: '' }).located, false);
  assert.match(read('api/assembler/list.js'), /serviceArea: describeEaserServiceArea\(profile\)/);
  assert.match(read('api/assembler/work-preferences.js'), /describeEaserServiceArea\(/);
  const owner = read('owner/index.html');
  assert.match(owner, /'<strong>Job area:<\/strong> ' \+ easerJobAreaText\(a\.serviceArea\)/);
  assert.match(owner, /Gets no job offers until it is fixed/);
  const profile = read('assembler/profile.html');
  assert.match(profile, /You get job offers within /);
  assert.match(profile, /payload\.travelRadiusMiles = Number\(radiusSelect\.value\)/);
});
await check('saving only the travel distance never resets the services or hours', () => {
  const api = read('api/assembler/work-preferences.js');
  assert.match(api, /const hasPreferences = Object\.prototype\.hasOwnProperty\.call\(body, 'services'\)/);
  assert.match(api, /const checked = hasPreferences \? normalizeWorkPreferences\(body, allServices\) : null;/);
});
await check('migration 132 adds the column the code reads, nullable, with a safety bound', () => {
  const sql = read('api/migrations/132_easer_travel_radius.sql');
  assert.match(sql, /ADD COLUMN IF NOT EXISTS travel_radius_miles SMALLINT;/);
  assert.match(sql, /CHECK \(travel_radius_miles IS NULL OR travel_radius_miles BETWEEN 5 AND 100\)/);
  assert.ok(TRAVEL_RADIUS_MILES.options.every(m => m >= 5 && m <= 100));
  assert.match(sql, /VALUES \(132, 'easer_travel_radius'\)/);
});

console.log(`service areas: ${passed} checks passed`);
