// Builds api/_texas-zip-locations.js: one point (latitude, longitude) for every
// Texas ZIP Code Tabulation Area, from the US Census Bureau Gazetteer. Dispatch
// measures the distance from an Easer's home ZIP to the job's ZIP with this
// table (api/_source-of-truth.js serviceAreaCheck), so it is data, not a guess.
//
//   node scripts/build-texas-zip-locations.mjs <path to 20XX_Gaz_zcta_national.txt> [year]
//
// Source: https://www.census.gov/geographies/reference-files/time-series/geo/gazetteer-files.html
// (public domain). The file lists every ZCTA with its internal point (INTPTLAT,
// INTPTLONG). Texas ZIPs are 733xx, 750xx-799xx and 885xx.
import { readFileSync, writeFileSync } from 'node:fs';

const [, , input, year = '2024'] = process.argv;
if (!input) {
  console.error('usage: node scripts/build-texas-zip-locations.mjs <Gaz_zcta_national.txt> [year]');
  process.exit(1);
}

const lines = readFileSync(input, 'utf8').split(/\r?\n/).filter(Boolean);
const header = lines.shift().split('\t').map(s => s.trim());
const col = name => {
  const i = header.indexOf(name);
  if (i < 0) throw new Error(`column ${name} missing from ${input}`);
  return i;
};
const [iZip, iLat, iLng] = [col('GEOID'), col('INTPTLAT'), col('INTPTLONG')];

const TEXAS = /^(733|7[5-9]\d|885)\d\d$/;
const rows = [];
for (const line of lines) {
  const cells = line.split('\t').map(s => s.trim());
  const zip = cells[iZip];
  if (!TEXAS.test(zip)) continue;
  const lat = Number(cells[iLat]);
  const lng = Number(cells[iLng]);
  if (!Number.isFinite(lat) || !Number.isFinite(lng)) throw new Error(`bad point for ${zip}`);
  // Texas sits inside 25.8-36.5 N, 93.5-106.7 W. Anything else is a bad row.
  if (lat < 25 || lat > 37 || lng < -107 || lng > -93) throw new Error(`${zip} is outside Texas: ${lat},${lng}`);
  rows.push([zip, Number(lat.toFixed(4)), Number(lng.toFixed(4))]);
}
rows.sort((a, b) => a[0].localeCompare(b[0]));
if (rows.length < 1900) throw new Error(`only ${rows.length} Texas ZCTAs; expected about 1,990`);

const body = rows.map(([zip, lat, lng]) => `'${zip}':[${lat},${lng}]`).join(',\n');
const out = `// GENERATED by scripts/build-texas-zip-locations.mjs. Do not edit by hand.
// One point per Texas ZIP Code Tabulation Area: [latitude, longitude], from the
// US Census Bureau ${year} Gazetteer (public domain). ${rows.length} ZIPs.
// Read it through zipLocation() in api/_source-of-truth.js, never directly.
export const TEXAS_ZIP_LOCATIONS_SOURCE = 'US Census Bureau ${year} Gazetteer, ZIP Code Tabulation Areas';
export const TEXAS_ZIP_LOCATIONS = Object.freeze({
${body},
});
`;
writeFileSync(new URL('../api/_texas-zip-locations.js', import.meta.url), out);
console.log(`wrote api/_texas-zip-locations.js: ${rows.length} Texas ZIPs`);
